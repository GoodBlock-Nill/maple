-- 20260910000800_inquiry_prefill_subtype_block
-- 프리필에 남은 "세부 문의 유형" 안내 블록만 걷어낸다(20260910000700 의 후속).
--
-- 앞 마이그레이션은 `prefill = <원본 시드>` 인 행만 고쳤다. 안전한 규칙이지만
-- **실제 운영 데이터에는 거의 맞지 않았다** — 운영자가 관리자 화면에서 예시 날짜를
-- 지우는 식의 손질을 이미 해 둔 행이 많아, 7개 중 5개가 블록을 그대로 안고 남았다.
-- 그 상태로 두면 사용자는 같은 것을 두 번 고른다(셀렉트 한 번, 본문 목록에서 한 번).
--
-- 그래서 여기서는 **그 블록만** 정규식으로 도려낸다.
--   · 지우는 범위: "세부 문의 유형" 으로 시작하는 줄 + 뒤따르는 목록 줄(- 또는 *)
--     + 블록 뒤의 빈 줄 하나
--   · 건드리지 않는 것: 나머지 모든 줄(운영자가 고쳐 둔 문구가 그대로 남는다)
--   · 대상: docs/1on1.md 시드 8종의 key 로 한정한다. 운영자가 직접 만든 카테고리의
--     양식은 그 안의 "세부 문의 유형" 이 무엇을 뜻하는지 우리가 알 수 없으므로 손대지 않는다.
--
-- 여러 번 돌려도 결과가 같다(두 번째부터는 일치하는 블록이 없어 아무 행도 바뀌지 않는다).
-- =============================================================================

update public.inquiry_categories
set prefill = regexp_replace(
      prefill,
      -- (^|\n) 를 그대로 되돌려(\1) 앞줄의 줄바꿈 구조를 유지한다.
      '(^|\n)세부 문의 유형[^\n]*\n(?:[-*][^\n]*\n)*\n?',
      '\1',
      'g'
    )
where key in (
        'connection',
        'character',
        'save-data',
        'currency',
        'content-balance',
        'account-environment',
        'feature-ui'
      )
  and prefill ~ '(^|\n)세부 문의 유형';
