-- =============================================================================
-- 답변 템플릿 — "이 문의에 이어서 남겨 주세요" 문구 정정
--
-- 배경
--   사용자 사이트의 홈페이지 문의는 접수 뒤 **사용자가 답글을 달 수 없다**(운영자 답변만
--   쌓인다). 그런데 시드 문안(20260911000200 · 20260914000200)은 추가 정보를 "이 문의에
--   이어서" 남겨 달라고 안내해, 사용자가 답글 칸을 찾다가 막힌다(오너 지적 2026-09-14).
--
-- 방침
--   추가 정보·재발 제보는 **새 문의로 접수**하되, 제목에 접수번호({{문의번호}})를 적어
--   달라고 안내한다 — 운영자가 이전 문의와 이어서 볼 수 있는 유일한 연결 고리가
--   접수번호다.
--
-- 방식
--   문장 단위 replace() 로 바꾼다. 운영자가 이미 고친 템플릿이라도 같은 문장이 남아
--   있으면 함께 고쳐지고, 문장을 이미 바꿨다면 아무 일도 일어나지 않는다. 재실행해도
--   안전하다.
-- =============================================================================

update public.inquiry_reply_templates
set body = replace(
  body,
  '받지 못하셨다면 이 문의에 이어서 알려 주세요.',
  '받지 못하셨다면 접수번호 {{문의번호}}를 적어 새 문의로 알려 주세요.'
)
where body like '%받지 못하셨다면 이 문의에 이어서 알려 주세요.%';

update public.inquiry_reply_templates
set body = replace(
  body,
  '다른 점이 있으면 이 문의에 이어서 남겨 주세요.',
  '다른 점이 있으면 접수번호 {{문의번호}}를 적어 새 문의로 남겨 주세요.'
)
where body like '%다른 점이 있으면 이 문의에 이어서 남겨 주세요.%';

update public.inquiry_reply_templates
set body = replace(
  body,
  '같은 문제가 다시 생기면 이 문의에 이어서 남겨 주세요.',
  '같은 문제가 다시 생기면 접수번호 {{문의번호}}를 적어 새 문의로 접수해 주세요.'
)
where body like '%같은 문제가 다시 생기면 이 문의에 이어서 남겨 주세요.%';

update public.inquiry_reply_templates
set body = replace(
  body,
  '점검이 끝난 뒤에도 같은 증상이 이어지면 접속 시각과 화면을 남겨 주세요. 이어서 확인하겠습니다.',
  '점검이 끝난 뒤에도 같은 증상이 이어지면 접속 시각과 화면을 담아 새 문의로 접수해 주세요. 제목에 접수번호 {{문의번호}}를 적어 주시면 이어서 확인하겠습니다.'
)
where body like '%점검이 끝난 뒤에도 같은 증상이 이어지면 접속 시각과 화면을 남겨 주세요. 이어서 확인하겠습니다.%';

/* 추가 정보 요청 계열 3종(추가 정보 요청 · 오류 재현 정보 요청 · 제보 증거 자료 요청).
   "남겨 주시면 …" 이 곧 답글을 뜻하므로 새 문의 접수 안내로 바꾼다. */
update public.inquiry_reply_templates
set body = replace(
  body,
  '남겨 주시면 이어서 확인하겠습니다.',
  '위 내용을 담아 새 문의로 접수해 주세요. 제목에 접수번호 {{문의번호}}를 적어 주시면 이어서 확인하겠습니다.'
)
where body like '%남겨 주시면 이어서 확인하겠습니다.%';

