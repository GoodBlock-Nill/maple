--   남아 있어야 "그때 무엇에 동의했는가"에 답할 수 있다. 다른 정책과 같은
--   개정 이력 위에 올려 두면 관리자가 화면에서 고치고 발행할 수 있다.
--
-- 슬러그 제약
--   `legal_documents_slug_known` 은 사용자 사이트의 `/policy/[slug]` 집합과 1:1 이다
--   (20260908002200). 여기에 `marketing` 하나를 더한다 — 제약을 지우지 않는 이유는
--   그대로다. 아무도 읽지 않는 문서가 조용히 쌓이는 것을 막는다.
-- =============================================================================

alter table public.legal_documents
  drop constraint if exists legal_documents_slug_known;

alter table public.legal_documents
  add constraint legal_documents_slug_known
  check (slug in ('privacy', 'discord', 'operating', 'marketing'));

