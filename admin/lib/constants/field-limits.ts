/**
 * 스키마가 따로 없는 입력의 길이 상한.
 *
 * 관리자 화면의 모든 텍스트 필드는 `현재 / 최대` 를 보여 준다(2026-09-09 운영
 * 요청). 저장되는 값은 모듈마다 zod 스키마가 상한을 쥐고 있지만, 목록 필터의
 * 검색어는 GET 폼으로 들어와 zod 를 거치지 않는다 — 화면에 적을 숫자가 없다.
 * 모듈마다 다른 값을 고르면 같은 모양의 검색칸이 화면마다 다른 말을 하므로
 * 여기 한 곳에 둔다.
 */

/**
 * 목록 검색어 상한.
 *
 * 문의 목록이 이미 서버에서 같은 길이로 자른다(`sanitizeInquirySearch`). 나머지
 * 목록도 그 숫자를 따라 60자로 맞춘다 — 닉네임(12) · 뉴스 제목(100)의 일부만
 * 넣어 찾는 칸이라 그보다 길 이유가 없다.
 */
export const SEARCH_MAX_LENGTH = 60

/** UUID 한 개의 길이. 감사 로그의 대상 ID 검색은 이보다 길 수 없다. */
export const UUID_LENGTH = 36

/**
 * 주소(URL · 경로) 입력의 기술적 상한.
 *
 * 실제로 들어오는 값은 Storage 공개 URL(≈150자)이나 `/images/...` 경로다.
 * 화면 표시 제약이 아니라 "이 이상은 주소가 아니다"라는 안전장치다.
 */
export const URL_MAX_LENGTH = 500

/** 이메일 주소의 실질 상한(RFC 5321 의 경로 길이). */
export const EMAIL_MAX_LENGTH = 254
